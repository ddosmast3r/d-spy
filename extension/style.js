export function buildPrompt(review, author, rating, orgTitle, examples) {
  const shots = examples.map(ex =>
    `ОТЗЫВ (автор: ${ex.author}, оценка: ${ex.rating}):\n${ex.review}\n\nОТВЕТ:\n${ex.reply}`
  ).join("\n\n---\n\n");
  return `${shots}\n\n---\n\nЗаведение: ${orgTitle}\n` +
    `ОТЗЫВ (автор: ${author || "имя неизвестно"}, оценка: ${rating || "нет"}):\n` +
    `${review}\n\nОТВЕТ:\n`;
}

// Приводим вывод модели к правилам, не надеясь на её послушность (порт _clean из replier.py).
export function cleanDraft(text, author) {
  text = (text || "").trim();
  text = text.replace(/^```[a-z]*\n?/i, "").replace(/```$/,"").trim();
  if (text.length > 1 && /["«']/.test(text[0]) && /["»']/.test(text[text.length-1])) {
    text = text.slice(1, -1).trim();
  }
  // правило 2: никаких длинных тире
  text = text.replace(/ — /g, ", ").replace(/—/g, ",");
  // правило 3: срезаем подпись
  text = text.replace(/\n+\s*(С уважением|Команда|Администрация)[^\n]*$/i, "").trim();

  // правило 1: приветствие отдельной строкой
  const greeting = author ? `Здравствуйте, ${author}!` : "Здравствуйте!";
  const nl = text.indexOf("\n");
  const first = nl === -1 ? text : text.slice(0, nl);
  let body;
  if (/^\s*(здравствуйте|добрый день|привет|доброго)/i.test(first)) {
    body = nl === -1 ? "" : text.slice(nl + 1).trim();
    if (!body) {
      const m = first.match(/^\s*([^!.\n]*[!.])\s*([\s\S]*)$/);
      if (m) { body = m[2].trim(); return `${m[1].trim()}\n${body}`.trim(); }
    }
  } else {
    body = text;
  }
  return `${greeting}\n${body}`.trim();
}
